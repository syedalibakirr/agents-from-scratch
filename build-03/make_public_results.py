#!/usr/bin/env python3
"""
Build 03: write the public results file.

FLOOD_TEST_RESULTS.md (written by run_test.py) holds the agent's full answers
about a private codebase, so it is gitignored. This script reads it and writes
RESULTS_BUILD3.md, which keeps everything needed to check the numbers:
question, condition, wall time, tool call count, every tool call with its
input, and fake-tool attempts.

Answers are replaced by their length, with one exception: a run that made
zero tool calls never saw the codebase, so its answer cannot contain private
code and is kept word for word. Those are the runs the finding is about.

Runs that crashed on a network error before the first model reply are listed
at the end and excluded from every count.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "FLOOD_TEST_RESULTS.md")
OUT = os.path.join(HERE, "RESULTS_BUILD3.md")

HEAD_RE = re.compile(r"^## Q(\d+) — (\w+)\s*$", re.M)


def field(block, name):
    m = re.search(r"\*\*" + re.escape(name) + r":\*\*\s*(.+)", block)
    return m.group(1).strip() if m else ""


def fenced_after(block, label):
    m = re.search(r"\*\*" + re.escape(label) + r"\*\*\s*```(.*?)```", block, re.S)
    return m.group(1).strip() if m else None


def final_answer(block):
    # The answer can contain its own ``` code blocks, so read to the LAST fence
    # in the run's section, not the first one.
    m = re.search(r"\*\*Final answer \(verbatim\):\*\*\s*```\n?(.*)```", block, re.S)
    return m.group(1).strip() if m else ""


def parse(text):
    heads = list(HEAD_RE.finditer(text))
    runs = []
    for i, m in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else len(text)
        b = text[m.end():end]
        calls = int(field(b, "Tool call count") or 0)
        tools = fenced_after(b, "Tools called, in order:")
        fake = re.search(r"\*\*Fake-tool attempts:\*\*\s*(.*?)\n\n", b, re.S)
        answer = final_answer(b)
        runs.append({
            "order": i + 1,
            "q": int(m.group(1)),
            "condition": m.group(2),
            "question": field(b, "Question"),
            "wall": field(b, "Wall time"),
            "calls": calls,
            "tools": tools.splitlines() if tools else [],
            "fake": fake.group(1).strip() if fake else "(none)",
            "answer": answer,
            "crashed": "agent crashed" in b,
        })
    return runs


def main():
    runs = parse(open(SRC, encoding="utf-8").read())
    valid = [r for r in runs if not r["crashed"]]
    crashed = [r for r in runs if r["crashed"]]
    out = []
    w = out.append

    w("# Build 03: public results\n")
    w("Generated by `make_public_results.py` from the private `FLOOD_TEST_RESULTS.md`.")
    w("Every tool call and its input is here. The agent's answers about the private")
    w("codebase are replaced by their length. Answers from runs with zero tool calls")
    w("are kept word for word: those runs never opened the codebase.\n")
    w(f"Valid runs: {len(valid)}. Crashed on a network error and excluded: {len(crashed)}.\n")

    w("## Every valid run\n")
    w("| # | Q | Condition | Wall time | Tool calls | Fake-tool attempts |")
    w("|---|---|---|---|---|---|")
    for r in valid:
        w(f"| {r['order']} | Q{r['q']} | `{r['condition']}` | {r['wall']} | {r['calls']} | {r['fake']} |")
    w("")

    w("## Run by run\n")
    for r in valid:
        w(f"### Run {r['order']}: Q{r['q']}, `{r['condition']}`\n")
        w(f"**Question:** {r['question']}  ")
        w(f"**Wall time:** {r['wall']} · **Tool calls:** {r['calls']} · **Fake-tool attempts:** {r['fake']}\n")
        if r["tools"]:
            w("```")
            w("\n".join(r["tools"]))
            w("```")
        else:
            w("Tools called: none.")
        w("")
        if r["calls"] == 0:
            w("**Final answer (word for word; no tool calls, so no private code):**\n")
            w("```")
            w(r["answer"])
            w("```")
        else:
            w(f"**Final answer:** [redacted: {len(r['answer'])} chars about a private codebase]")
        w("")

    w("## Excluded runs\n")
    w("These crashed with `anthropic.APIConnectionError` (a network drop) before the")
    w("model replied once, then were re-run. They are not counted anywhere.\n")
    w("| # | Q | Condition |")
    w("|---|---|---|")
    for r in crashed:
        w(f"| {r['order']} | Q{r['q']} | `{r['condition']}` |")
    w("")

    open(OUT, "w", encoding="utf-8").write("\n".join(out))
    print(f"wrote {OUT}: {len(valid)} valid, {len(crashed)} excluded")


if __name__ == "__main__":
    main()
